"""
Extracts the swarm (busy) periods from the BohemiaSaxony catalog.

Noise traces for BohemiaSaxony are taken from quiet periods only, outside the
windows written here, see ROADMAP.md. A day is busy if it has at least
``--busy`` catalog events. Busy days at most ``--gap`` quiet days apart form one
window, windows with fewer than ``--min-events`` events are dropped, and each
window is padded by ``--pad`` days on both sides.

    uv run python scripts/bohemia_swarms.py <dataset>/metadata.csv
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

OUTPUT = Path(__file__).parents[1] / "src/seisbench_datasets/data/bohemia_swarms.csv"


def find_swarms(
    events: pd.DataFrame,
    busy: int = 10,
    gap: int = 3,
    min_events: int = 50,
    pad: int = 1,
) -> pd.DataFrame:
    """
    :param events: One row per event, with ``time`` (UTC) and ``magnitude``
    :return: One row per window: ``start``, ``end`` (exclusive), ``n_events``,
        ``max_events_per_day`` and ``max_magnitude``
    """
    day = events["time"].dt.floor("D")
    daily = day.value_counts().sort_index()

    groups: list[list[pd.Timestamp]] = []
    for busy_day in daily[daily >= busy].index:
        if groups and (busy_day - groups[-1][1]).days <= gap + 1:
            groups[-1][1] = busy_day
        else:
            groups.append([busy_day, busy_day])

    rows = []
    for first, last in groups:
        inside = events[(day >= first) & (day <= last)]
        if len(inside) < min_events:
            continue
        rows.append(
            {
                "start": first - pd.Timedelta(days=pad),
                "end": last + pd.Timedelta(days=1 + pad),
                "n_events": len(inside),
                "max_events_per_day": int(daily[first:last].max()),
                "max_magnitude": inside["magnitude"].max(),
            }
        )
    return pd.DataFrame(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("metadata", type=Path, help="metadata.csv of BohemiaSaxony")
    parser.add_argument("--busy", type=int, default=10)
    parser.add_argument("--gap", type=int, default=3)
    parser.add_argument("--min-events", type=int, default=50)
    parser.add_argument("--pad", type=int, default=1)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    metadata = pd.read_csv(
        args.metadata,
        usecols=["source_id", "source_origin_time", "source_magnitude"],
    )
    events = metadata.drop_duplicates("source_id")
    events = pd.DataFrame(
        {
            "time": pd.to_datetime(events["source_origin_time"], utc=True),
            "magnitude": events["source_magnitude"],
        }
    )
    swarms = find_swarms(events, args.busy, args.gap, args.min_events, args.pad)

    days = (swarms["end"] - swarms["start"]).dt.days.sum()
    header = (
        "# Swarm (busy) periods of the BohemiaSaxony catalog. Noise is taken outside.\n"
        f"# Generated by scripts/bohemia_swarms.py on {datetime.now(timezone.utc):%Y-%m-%d}"
        f" from {len(events)} events ({events['time'].min():%Y-%m-%d} to "
        f"{events['time'].max():%Y-%m-%d}).\n"
        f"# Busy day: >= {args.busy} events. Merged across <= {args.gap} quiet days, "
        f">= {args.min_events} events per window, padded by {args.pad} day(s).\n"
        f"# {len(swarms)} windows, {days} days, "
        f"{swarms['n_events'].sum()} events. end is exclusive.\n"
    )
    for column in ("start", "end"):
        swarms[column] = swarms[column].dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    with open(args.output, "w") as f:
        f.write(header)
        swarms.to_csv(f, index=False, float_format="%.1f")
    print(header, end="")
    print(f"Written to {args.output}")


if __name__ == "__main__":
    main()
